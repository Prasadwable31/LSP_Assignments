int Addition(int A, int B)
{
    int Sum = 0;
    Sum = A + B;

    return Sum;
}

int Substraction(int A, int B)
{
    int Sum = 0;
    Sum = A - B;
    
    return Sum;
}

int Multiplication(int A, int B)
{
    int Mul = 0;
    Mul = A * B;
    
    return Mul;
}

int Division(int A, int B)
{
    int Div = 0;
    Div = A / B;
    
    return Div;
}